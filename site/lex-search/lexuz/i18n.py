def _tr(value, script: str):
    if isinstance(value, str):
        return uzbek.translit(value, script)
    if isinstance(value, list):
        return [_tr(v, script) for v in value]
    if isinstance(value, dict):
        return {k: _tr(v, script) for k, v in value.items()}
    return value


